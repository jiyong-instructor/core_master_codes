// 3. 배열: 여러 값을 순서대로 담는 자료형
const 쇼핑리스트 = ["컴퓨터", "핸드폰", "티켓"]

console.log(쇼핑리스트)
쇼핑리스트.push("시계")
console.log(쇼핑리스트)

// 4. 객체: 이름표(key)와 값(value)을 한 묶음으로 저장하는 자료형
const 학생 = {
    이름: "철수",
    나이: 12,
    취미: "축구",
    isGraduated: false,
}

console.log(학생)
console.log(학생.이름)
console.log(학생.나이)

// 객체 안의 값은 점 표기법으로 꺼낼 수 있습니다.
학생.취미 = "농구"
console.log(학생)

// 5. 배열 안에 객체를 넣으면 여러 사람의 정보를 한 번에 관리할 수 있습니다.
