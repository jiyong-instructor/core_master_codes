// 주석은 나중에 다시 볼 때 내용을 빠르게 이해하도록 도와주는 메모입니다.

// 1. 가장 많이 쓰는 변수 선언 키워드
var 옛날방식 = "var는 예전부터 쓰던 변수 선언 방식입니다"
let 바뀔수있는값 = "처음에는 let으로 선언해두고 나중에 바꿀 수 있습니다"
const 바뀌지않는값 = "const는 다시 대입하지 않을 값에 사용합니다"

console.log(옛날방식)
console.log(바뀔수있는값)
console.log(바뀌지않는값)

바뀔수있는값 = "let은 다시 값을 넣을 수 있습니다"
console.log(바뀔수있는값)

// 2. 자바스크립트의 기본 데이터 타입 예시
