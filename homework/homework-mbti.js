function 연애궁합확인하기() {
    const 상대유형 = document.getElementById("상대엠비티아이").value
    const 나의결과 = 엠비티아이결과목록[나의엠비티아이]
    let 같은글자수 = 0

    for (let 번호 = 0; 번호 < 4; 번호 = 번호 + 1) {
        if (나의엠비티아이[번호] === 상대유형[번호]) 같은글자수 = 같은글자수 + 1
    }

    let 궁합문구 = "재난 로맨스 🎢 이해는 안 되는데 웃겨서 계속 만나요. 친구들이 다음 화를 기다려요."
    let 궁합점수 = 52

    if (나의엠비티아이 === 상대유형) {
        궁합문구 = "거울 연애 🪞 같은 타이밍에 삐지고 같은 타이밍에 배고파져요. 배달앱이 중재자예요."
        궁합점수 = 88
    } else if (나의결과.찰떡.indexOf(상대유형) !== -1) {
        궁합문구 = "찰떡 연애 💘 카톡 텐션도, 쉬는 타이밍도 절묘해요. 친구들이 단체로 질투해요."
        궁합점수 = 96
    } else if (같은글자수 >= 3) {
        궁합문구 = "복붙 연애 🧬 설명서는 필요 없지만 같은 단점에서 동시에 미끄러질 수 있어요."
        궁합점수 = 83
    } else if (같은글자수 === 2) {
        궁합문구 = "단짠 연애 🍟 평소엔 티키타카, 싸우면 서로 다른 언어라 자막이 필요해요."
        궁합점수 = 71
    }

    document.getElementById("궁합결과").innerHTML = `<strong>${나의엠비티아이} × ${상대유형} · ${궁합점수}점</strong><br />${궁합문구}`
}
